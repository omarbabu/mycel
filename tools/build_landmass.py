"""Convert Natural Earth 110m land GeoJSON into a compact JS module for the offline map.

Usage: python3 -I tools/build_landmass.py <ne_110m_land.geojson> <out.js>
"""
import json
import sys


def simplify(ring, step=0.6):
    out = []
    for lon, lat in ring:
        p = (round(lon, 1), round(lat, 1))
        if not out or abs(p[0] - out[-1][0]) + abs(p[1] - out[-1][1]) >= step:
            out.append(p)
    return out if len(out) >= 4 else []


def main(src, dst):
    with open(src) as f:
        data = json.load(f)
    rings = []
    for feat in data["features"]:
        geom = feat["geometry"]
        polys = [geom["coordinates"]] if geom["type"] == "Polygon" else geom["coordinates"]
        for poly in polys:
            r = simplify(poly[0])
            if r:
                rings.append([c for pt in r for c in pt])
    with open(dst, "w") as f:
        f.write("// Natural Earth 110m land (public domain), simplified. Generated by tools/build_landmass.py\n")
        f.write("window.LAND_RINGS=" + json.dumps(rings, separators=(",", ":")) + ";\n")
    print(f"{len(rings)} rings, {sum(len(r) for r in rings)//2} points")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
